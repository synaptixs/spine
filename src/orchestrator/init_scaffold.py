"""``orchestrator init`` — scaffold a new project to use the orchestrator (G14).

The companion to ``doctor``: ``doctor`` *checks* environment readiness;
``init`` *writes the scaffold* for it. It generates a commented ``.env``
skeleton from the same ``ENV_GROUPS`` doctor checks (so the two never drift),
filling in only the keys that aren't already set — it never overwrites an
existing value, so re-running it is safe and only adds what's missing.

Pure functions (``render_env_template`` / ``missing_keys``) carry the logic so
they're unit-testable; the CLI command wires file I/O around them.
"""

from __future__ import annotations

from collections.abc import Mapping
from pathlib import Path

from orchestrator.core.llm import catalog
from orchestrator.doctor import ENV_GROUPS

# Known-useful optional vars worth scaffolding as commented hints, beyond the
# required groups doctor enforces.
_OPTIONAL_HINTS: tuple[tuple[str, str], ...] = (
    # Model selection was scaffolded nowhere, so the only way to learn a stage could be
    # pointed somewhere else was to read the source — and three of the four stages could
    # not be pointed anywhere at all. `orchestrator models` lists the ids with prices and
    # marks the ones that cannot do the forced tool call codegen and the judge require.
    (
        "ORCHESTRATOR_MODEL",
        f"Model for every stage (default {catalog.DEFAULT_MODEL}); see `orchestrator models`",
    ),
    ("SDLC_CODEGEN_MODEL", "Model for codegen only — implement / refine / revise / author_tests"),
    ("SDLC_JUDGE_MODEL", "Model for the acceptance judge only"),
    ("ORCHESTRATOR_INTAKE_MODEL", "Model for intake only — intent extraction and spec writing"),
    (
        "ORCHESTRATOR_IDEATION_MODEL",
        "Model for generated solution options only (falls back to the intake model); one capped call",
    ),
    # Not just the PR target: an SDLC run *branches from* this, so leaving it unset builds
    # the work on the remote's default branch (usually main) while opening the PR into
    # develop — a change written against a tree that predates everything merged since the
    # last release. It was documented nowhere until that bit someone.
    (
        "SDLC_PR_BASE",
        "Branch a run builds on AND opens its PR into (default: the remote's default branch)",
    ),
    # B155: the three settings a first build depends on, none of which `init` wrote. Without the first,
    # `sdlc feature` builds in an empty scratch repository with none of the user's code around it.
    (
        "SDLC_REPO_URL",
        "Repo a run clones and builds in; unset, builds run in an empty scratch repo and --live refuses",
    ),
    ("GITHUB_TOKEN", "GitHub token (or GH_TOKEN) for a private target repository and for opening live PRs"),
    (
        "JIRA_DRY_RUN",
        "1 = print tracker writes instead of making them; the safety switch for the Jira credentials above",
    ),
    ("ORCHESTRATOR_DATABASE_URL", "Postgres URL (defaults to the docker-compose dev DB)"),
    ("SLACK_WEBHOOK_URL", "Slack incoming-webhook for approval-gate alerts (optional)"),
    ("SDLC_RUN_BUDGET_USD", "Per-run LLM spend cap; 0 disables enforcement (default 25)"),
    ("NOTION_API_TOKEN", "Notion integration token, if sourcing requirements from Notion"),
)


def render_env_template(existing: Mapping[str, str] | None = None) -> str:
    """Render a ``.env`` skeleton from ENV_GROUPS, omitting already-set keys.

    Every required var doctor checks gets a ``NAME=`` line under a commented
    group header; vars already present in ``existing`` are skipped (init only
    adds what's missing). Optional vars are listed, commented out, as hints.
    """
    existing = existing or {}
    lines: list[str] = [
        "# Orchestrator configuration — generated by `orchestrator init`.",
        "# Fill in the blanks, then run `orchestrator doctor` to verify.",
        "",
    ]
    for group in ENV_GROUPS:
        pending = [v for v in group.variables if v.name not in existing]
        if not pending:
            continue
        header = f"# --- {group.name} ---"
        if group.note:
            header += f"  ({group.note})"
        lines.append(header)
        for var in pending:
            if var.hint:
                lines.append(f"# {var.hint}")
            lines.append(f"{var.name}=")
        lines.append("")

    optional_pending = [(n, h) for n, h in _OPTIONAL_HINTS if n not in existing]
    if optional_pending:
        lines.append("# --- Optional ---")
        for name, hint in optional_pending:
            lines.append(f"# {hint}")
            lines.append(f"# {name}=")
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def missing_keys(existing: Mapping[str, str]) -> list[str]:
    """Required env vars (from ENV_GROUPS) not present in ``existing``."""
    out: list[str] = []
    for group in ENV_GROUPS:
        for var in group.variables:
            if var.name not in existing:
                out.append(var.name)
    return out


def parse_env_file(text: str) -> dict[str, str]:
    """Minimal ``.env`` parse: ``KEY=value`` lines, ignoring blanks/comments.

    Only the key set matters here (init checks which keys already exist), so
    values are kept verbatim without unquoting.
    """
    env: dict[str, str] = {}
    for raw in text.splitlines():
        line = raw.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, _, value = line.partition("=")
        key = key.strip()
        if key:
            env[key] = value.strip()
    return env


def ignore_in_git(env_path: Path) -> str:
    """Make sure git ignores ``env_path``; say what was done, or ``""`` when nothing needed saying.

    B154: ``init`` wrote the file the reader is told to put every key into, in the repository root, and
    never looked at ``.gitignore``, so a ``git add -A`` committed the keys. When ``env_path`` sits in a
    git work tree that does not already ignore it, its name is appended to the work tree's top-level
    ``.gitignore``. Re-running adds nothing. A ``.env`` git already *tracks* is beyond a ``.gitignore``,
    so that case is said loudly instead. Outside a work tree, or without git, nothing is done.
    """
    import shutil
    import subprocess

    if shutil.which("git") is None:
        return ""
    where = env_path.parent

    def git(*args: str) -> subprocess.CompletedProcess[str]:
        return subprocess.run(["git", "-C", str(where), *args], capture_output=True, text=True, check=False)

    top = git("rev-parse", "--show-toplevel")
    if top.returncode != 0:
        return ""
    root = Path(top.stdout.strip())
    if git("ls-files", "--error-unmatch", env_path.name).returncode == 0:
        return (
            f"WARNING: git already tracks {env_path}, so a .gitignore entry cannot protect it. "
            f"Untrack it before adding keys: git rm --cached {env_path}"
        )
    if git("check-ignore", "-q", env_path.name).returncode == 0:
        return ""
    gitignore = root / ".gitignore"
    entry = "/" + env_path.resolve().relative_to(root.resolve()).as_posix()
    current = gitignore.read_text(encoding="utf-8") if gitignore.exists() else ""
    sep = "" if not current or current.endswith("\n") else "\n"
    gitignore.write_text(f"{current}{sep}{entry}\n", encoding="utf-8")
    return f"Added {entry} to {gitignore}, so git will not commit the keys it holds."


def scaffold_env(path: Path, *, force: bool = False) -> tuple[bool, list[str]]:
    """Write/extend a ``.env`` at ``path``. Returns (wrote_file, keys_added).

    - No file (or ``force``): write a fresh template; ``keys_added`` is every
      required key.
    - Existing file: append only the required keys it's missing, preserving
      everything already there; ``keys_added`` is what was appended (possibly
      empty, in which case nothing is written).
    """
    if path.exists() and not force:
        current = parse_env_file(path.read_text(encoding="utf-8"))
        to_add = missing_keys(current)
        if not to_add:
            return False, []
        snippet = render_env_template(current)
        body = path.read_text(encoding="utf-8").rstrip() + "\n\n" + snippet
        path.write_text(body, encoding="utf-8")
        return True, to_add

    path.write_text(render_env_template({}), encoding="utf-8")
    return True, missing_keys({})


